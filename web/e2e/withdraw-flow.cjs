// Withdraw and come back: bet -> withdraw (two taps) -> the low-balance notice offers to move the
// wallet's NEAR back -> one tap -> game balance restored. usage: node e2e/withdraw-flow.cjs <url>
const puppeteer = require(process.env.PUPPETEER || 'puppeteer')
const URL = process.argv[2] || 'http://127.0.0.1:5044/'
const sleep = ms => new Promise(r => setTimeout(r, ms))
const click = (p, re) => p.evaluate(src => { const r = new RegExp(src); const b = [...document.querySelectorAll('button')].find(x => r.test(x.textContent.trim())); if (!b) return false; b.click(); return true }, re.source)
;(async () => {
  const b = await puppeteer.launch({ headless: 'new', args: ['--no-sandbox'], protocolTimeout: 10 * 60_000 })
  const p = await b.newPage()
  const errors = []
  p.on('pageerror', e => errors.push(String(e)))
  await p.setViewport({ width: 390, height: 844, isMobile: true, hasTouch: true })
  await p.goto(URL, { waitUntil: 'networkidle2' })
  await p.waitForSelector('.answer.B', { timeout: 120_000 })
  await p.tap('.answer.B'); await p.tap('.cta')
  await p.waitForFunction(() => document.querySelector('.sealed') || document.querySelector('.toast.err'), { timeout: 120_000 })
  if (await p.$('.toast.err')) throw new Error('bet failed: ' + await p.$eval('.toast.err', e => e.innerText))
  await p.goto(URL + '#/me', { waitUntil: 'networkidle2' })
  await p.waitForSelector('.wallet', { timeout: 60_000 })
  await sleep(3000)
  const before = await p.$eval('.money', e => e.innerText)
  console.log('game balance', before, '| wallet line:', (await p.$eval('.wallet', e => e.innerText)).replace(/\s+/g, ' '))
  if (!(await click(p, /^Withdraw to the wallet/))) throw new Error('no withdraw button')
  await sleep(300)
  console.log('confirm step:', (await p.$eval('.confirm', e => e.innerText)).replace(/\s+/g, ' ').slice(0, 140))
  await click(p, /^Withdraw$/)
  await p.waitForFunction(() => /moved to your wallet/.test(document.body.innerText) || document.querySelector('.toast.err'), { timeout: 120_000 })
  await sleep(4000)
  console.log('after withdraw: game', await p.$eval('.money', e => e.innerText), '| wallet line:', (await p.$eval('.wallet', e => e.innerText)).replace(/\s+/g, ' '))
  await p.goto(URL + '#/', { waitUntil: 'networkidle2' })
  await p.waitForSelector('.low', { timeout: 60_000 })
  console.log('Play page notice:', (await p.$eval('.low', e => e.innerText)).replace(/\s+/g, ' '))
  await p.evaluate(() => document.querySelector('.low .btn').click())
  await p.waitForFunction(() => /into your game balance/.test(document.body.innerText) || document.querySelector('.toast.err'), { timeout: 120_000 })
  await sleep(4000)
  console.log('notice still there?', !!(await p.$('.low')), '| header:', await p.$eval('.right', e => e.innerText.replace(/\s+/g, ' ')))
  console.log('errors:', errors.length ? errors : 'none')
  await b.close()
})().catch(e => { console.error('E2E FAILED', e.message); process.exit(1) })
