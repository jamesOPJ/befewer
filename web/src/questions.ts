export const QUESTIONS: Question[] = RAW.map(([q, a, b]) => ({ q, a, b }))

export function questionFor(round: number | string): Question {
  const r = Number(round)
  return QUESTIONS[((r % QUESTIONS.length) + QUESTIONS.length) % QUESTIONS.length]
}

export function label(round: number | string, side: 'A' | 'B' | 'void' | null | undefined): string {
  if (side !== 'A' && side !== 'B') return side ?? '?'
  const q = questionFor(round)
  return side === 'A' ? q.a : q.b
}
